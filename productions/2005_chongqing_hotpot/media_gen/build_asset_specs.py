def main():
    proj = json.loads(PROJ_JSON.read_text(encoding="utf-8"))
    chars_list = json.loads(CHARS_DB.read_text(encoding="utf-8"))
    global_map = {c["character_key"]: c for c in chars_list}

    out = {
        "projectId": proj["id"],
        "stylePrompt": PROJECT_STYLE_PROMPT,
        "characters": [],
        "scenes": [],
        "props": [],
    }

    for a in proj["assets"]:
        aid = a["id"]
        name = a["name"]
        atype = a["type"]
        if atype == "character":
            cfg = CHAR_OUTFITS[name]
            base_name = cfg["base"]
            ckey = BASE_IDENTITY_MAP[base_name]
            gc = global_map[ckey]
            cdir = GEN_ROOT / ckey
            face_calm = str(cdir / "face_平静_2k.png")
            assert Path(face_calm).is_file(), f"Missing {face_calm}"
            ref_expr_name = cfg.get("ref_expr")
            face_expr_ref = None
            if ref_expr_name and (cdir / f"face_{ref_expr_name}_2k.png").is_file():
                face_expr_ref = str(cdir / f"face_{ref_expr_name}_2k.png")
            voice_wav = str(VOICES_DIR / f"{ckey}.wav")
            assert Path(voice_wav).is_file(), f"Missing {voice_wav}"

            out["characters"].append({
                "assetId": aid,
                "name": name,
                "baseName": base_name,
                "globalCharacterKey": ckey,
                "globalCharacterName": gc["character_name"],
                "gender": gc.get("gender", ""),
                "ageDesc": cfg.get("age_override") or gc.get("age_desc", ""),
                "description": cfg.get("desc_override") or a.get("description", ""),
                "faceAndBodyDesc": gc.get("face_and_body_desc", ""),
                "hairDesc": cfg["hair"],
                "outfitDesc": cfg["outfit"],
                "exprLabel": cfg["expr_label"],
                "exprDesc": cfg["expr_desc"],
                "faceCalmRef": face_calm,
                "faceExprRef": face_expr_ref,
                "voiceWav": voice_wav,
                "prompt": f"精致明亮电影质感写实人物设定（全局角色原型 {ckey} {gc['character_name']}，{cfg.get('age_override') or gc.get('age_desc','')}）：{gc.get('face_and_body_desc','')}；发型：{cfg['hair']}；穿搭：{cfg['outfit']}。纯白背景 RGB(255,255,255)，五格人物资产图（无头正面全身、无头90°左侧全身、完整背面全身、正面平静面部图、{cfg['expr_label']}表情图）。",
            })
        elif atype == "scene":
            assert name in SCENE_PROMPTS, f"Missing scene prompt: {name}"
            out["scenes"].append({
                "assetId": aid,
                "name": name,
                "prompt": SCENE_PROMPTS[name],
            })
        elif atype == "prop":
            assert name in PROP_PROMPTS, f"Missing prop prompt: {name}"
            out["props"].append({
                "assetId": aid,
                "name": name,
                "prompt": PROP_PROMPTS[name],
            })

    OUT_SPEC.parent.mkdir(parents=True, exist_ok=True)
    OUT_SPEC.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Saved {OUT_SPEC}: {len(out['characters'])} chars ({len(set(x['globalCharacterKey'] for x in out['characters']))} unique global identities), {len(out['scenes'])} scenes, {len(out['props'])} props")

if __name__ == "__main__":
    main()
